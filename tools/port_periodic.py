"""Port the Periodic Table Builder into openstudio as a Studio module.

    python tools/port_periodic.py [path/to/openperiodictable]

Reads the builder's template (codes/app_data/app_template.html) and data builder (codes/app_data/make_app_data.py) from the
openperiodictable repo and writes:
  data/periodic.json            the builder's data blob (118 elements, Lavoisier's 33, K-alpha energies)
  styles/periodic.css           the builder's stylesheet, every selector scoped under .ptb
  src/workspaces/periodic.js    the builder's script wrapped as mount(host, data, opts)
The builder keeps one source of truth (openperiodictable); this script is the only place that knows how it is wrapped.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.join(os.path.dirname(ROOT), "openperiodictable-repo")
APP = os.path.join(SRC, "codes", "app_data")


def split_rules(css):
    """Yield (prelude, body) for each top-level rule; body excludes the outer braces."""
    i, n = 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j < 0:
            break
        depth, k = 1, j + 1
        while depth and k < n:
            depth += {"{": 1, "}": -1}.get(css[k], 0)
            k += 1
        yield css[i:j].strip(), css[j + 1 : k - 1]
        i = k


def scope(css):
    out = []
    for pre, body in split_rules(css):
        if pre.startswith("@media"):
            if "prefers-color-scheme" in pre:
                continue  # the Studio sets data-theme on <html> itself
            out.append(pre + " {\n" + scope(body) + "\n}")
        elif pre.startswith("@"):
            out.append(pre + " {" + body + "}")
        else:
            sels = []
            for s in (x.strip() for x in pre.split(",")):
                if s.startswith(":root[data-theme"):
                    sels.append(s + " .ptb")
                elif s == ":root":
                    sels.append(".ptb")
                elif s in ("html", "body"):
                    sels.append(".ptb")
                else:
                    sels.append(".ptb " + s)
            out.append(", ".join(sels) + " {" + body + "}")
    return "\n".join(out)


def main():
    tpl = open(os.path.join(APP, "app_template.html"), encoding="utf-8").read()
    css = re.search(r"<style>(.*?)</style>", tpl, re.S).group(1)
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S).replace("#rail", "#ptb-rail").replace("#stage", "#ptb-stage")
    scoped = scope(css)
    open(os.path.join(ROOT, "styles", "periodic.css"), "w", encoding="utf-8", newline="\n").write(
        "/* Generated by tools/port_periodic.py from the Periodic Table Builder stylesheet. Do not edit by hand. */\n" + scoped
        + "\n.ptb { background: transparent; padding: 0; margin: 0 -2px; }\n.ptb-note { color: var(--muted); font-size: .85rem; margin-top: 18px; }\n"
    )

    js = re.search(r"<script>(.*?)</script>", tpl, re.S).group(1)
    js = js.replace('"use strict";', "", 1)
    assert "var D = /*DATA*/ null;" in js
    js = js.replace("var D = /*DATA*/ null;", "")
    js = js.replace('document.getElementById("rail")', 'host.querySelector("#ptb-rail")')
    js = js.replace('document.getElementById("stage")', 'host.querySelector("#ptb-stage")')
    # drop the stand-alone theme toggle and hash handling; the Studio owns both
    js = re.sub(r'\s*document\.getElementById\("theme"\)\.addEventListener\("click", function \(\) \{.*?\}\);\s*var m = /\^#s\(\[1-5\]\)\$/\.exec\(location\.hash\);\s*go\(m \? parseInt\(m\[1\], 10\) - 1 : 0\);',
                "\n      go(Math.min(4, Math.max(0, (parseInt(opts.stage, 10) || 1) - 1)));", js, flags=re.S)
    assert "opts.stage" in js, "theme/hash tail not found; the template changed"
    js = js.replace("getComputedStyle(document.documentElement)", 'getComputedStyle(host.querySelector(".ptb"))')
    assert 'host.querySelector(".ptb")' in js
    js = js.replace('history.replaceState(null, "", "#s" + (i + 1));', 'history.replaceState(null, "", "#periodic?stage=" + (i + 1));')
    assert "#periodic?stage" in js

    head = (
        "// Generated by tools/port_periodic.py from the Periodic Table Builder (openperiodictable). Do not edit by hand.\n"
        "// mount(host, data, opts): renders the five-stage builder into host. opts.stage is 1..5.\n"
        "export function mount(host, D, opts) {\n"
        "  opts = opts || {};\n"
        '  host.innerHTML = \'<div class="ptb"><nav class="rail" id="ptb-rail" aria-label="Stages"></nav>\'\n'
        '    + \'<main id="ptb-stage" class="panel" tabindex="-1"></main>\'\n'
        '    + \'<p class="ptb-note">Data: Lavoisier\\u0027s 1789 table (33 entries); K-alpha energies from the X-ray Data Booklet (LBNL); \'\n'
        '    + \'atomic weights are rounded abridged values typed from general knowledge, and discoverers are approximate. Check both before quoting.</p></div>\';\n'
    )
    open(os.path.join(ROOT, "src", "workspaces", "periodic.js"), "w", encoding="utf-8", newline="\n").write(head + js + "\n}\n")

    sys.path.insert(0, APP)
    sys.path.insert(0, os.path.join(SRC, "codes", "chemistry", "lavoisier"))
    sys.path.insert(0, os.path.join(SRC, "codes", "xray", "moseley"))
    import make_app_data  # noqa: E402

    blob = make_app_data.build()
    with open(os.path.join(ROOT, "data", "periodic.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(blob, f, ensure_ascii=False, separators=(",", ":"))
        f.write("\n")
    print("wrote styles/periodic.css, src/workspaces/periodic.js, data/periodic.json (%d elements)" % len(blob["els"]))


if __name__ == "__main__":
    main()
